"""The plugin's domain contract: entities, enums, errors and ``Protocol``s.

Source of truth for the implementation modules, which only see this file and the fakes in
``tests/fakes/``. General rules:

- **Time**: every ``*_at`` is a ``Timestamp`` = whole seconds since the Unix epoch (UTC). No date
  strings in the database or in the types; the interface formats.
- **Ids**: channel = ``UC`` + 22 characters; video = 11 characters; other entities = an opaque
  ``str`` generated by the owner (``uuid4().hex`` recommended). Exception: ``changes.id`` is an
  increasing integer (history order).
- **Who writes**: only the owner of each table. The others go through the service. Reading any
  table directly is allowed.
- **Services that write history** take an ``actor`` and call ``ChangeLog.record``.
- **Blocking operations** (``Organizer.organize``, ``Cleanup.scan``, ``Themes.create``,
  ``ListImporter.import_list``, ``Refresher.refresh_all``) take ``timeout`` and ``on_progress``;
  they raise ``OperationTimeout`` when it runs out. REST routes never call them (only
  ``JobRunner`` or ``Refresher.kick_if_due``).
- **Construction**: each module exports ``build(*, <named deps>)`` as in ``BUILDS``; every
  ``build`` in ``core/`` also accepts ``clock: Clock | None = None``.
- Nothing here imports Hermes or does network.
"""

