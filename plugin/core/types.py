def _str_tuple(value: Any, where: str) -> tuple[str, ...]:
    if not isinstance(value, list | tuple) or not all(isinstance(v, str) for v in value):
        raise ValidationError(f"{where}: expected a list of strings", field=where)
    return tuple(value)


def _flag(value: Any, where: str) -> bool:
    if not isinstance(value, bool):
        raise ValidationError(f"{where}: expected a boolean", field=where)
    return value


def _opt_int(value: Any, where: str, minimum: int) -> int | None:
    if value is None:
        return None
    if isinstance(value, bool) or not isinstance(value, int) or value < minimum:
        raise ValidationError(f"{where}: expected an integer ≥ {minimum} or null", field=where)
    return value


def _mapping(value: Any, where: str, allowed: Sequence[str]) -> Mapping[str, Any]:
    if value is None:
        return {}
    if not isinstance(value, Mapping):
        raise ValidationError(f"{where}: expected an object", field=where)
    unknown = sorted(set(value) - set(allowed))
    if unknown:
        raise ValidationError(f"{where}: unknown keys {unknown}", field=where)
    return value


