def to_jsonable(value: Any) -> Any:
    """Convert dataclasses, enums, tuples and mappings to plain JSON (properties are left out)."""
    if dataclasses.is_dataclass(value) and not isinstance(value, type):
        # an empty optional output field (``metadata={"optional": True}``, additive) is left out:
        # the previous JSON stays identical while the new data does not exist
        return {
            f.name: to_jsonable(getattr(value, f.name))
            for f in dataclasses.fields(value)
            if not (f.metadata.get("optional") and getattr(value, f.name) is None)
        }
    if isinstance(value, enum.Enum):
        return value.value
    if isinstance(value, Mapping):
        return {str(to_jsonable(k)): to_jsonable(v) for k, v in value.items()}
    if isinstance(value, list | tuple | set | frozenset):
        return [to_jsonable(v) for v in value]
    if isinstance(value, bytes):
        return value.decode("utf-8", errors="replace")
    return value


