def _tuplify(value: Any) -> Any:
    if isinstance(value, list | tuple):
        return tuple(_tuplify(v) for v in value)
    if isinstance(value, Mapping):
        return {k: _tuplify(v) for k, v in value.items()}
    return value


def undo_to_dict(undo: UndoData) -> dict[str, Any]:
    """Serialise to ``changes.undo`` (JSON)."""
    return to_jsonable(undo)


def undo_from_dict(action: ChangeAction, data: Mapping[str, Any]) -> UndoData:
    """Rebuild the action's ``UndoData``; unknown/missing key → ``ValidationError``."""
    cls = UNDO_TYPES[ChangeAction(action)]
    names = {f.name for f in dataclasses.fields(cls)}
    unknown = set(data) - names
    if unknown:
        raise ValidationError(f"undo of {action}: unknown keys {sorted(unknown)}")
    try:
        return cls(**{k: _tuplify(v) for k, v in data.items()})
    except TypeError as exc:
        raise ValidationError(f"undo of {action}: {exc}") from exc


