@dataclass(frozen=True, slots=True)
class TabRules:
    """Tab rule (``tabs.rules``, JSON). The engine evaluates ``include − exclude → filters``.

    Muted channels (``muted``) stay out of ``all``/``folders``/``tags``/``favorites`` and only
    come in when listed in ``include.channels``. ``ignored`` and ``ex`` never come in through a
    folder/tag.
    """

    include: RuleInclude = field(default_factory=RuleInclude)
    exclude: RuleExclude = field(default_factory=RuleExclude)
    filters: RuleFilters = field(default_factory=RuleFilters)
    mode: FeedMode = FeedMode.fresh

    @classmethod
    def from_dict(cls, data: Mapping[str, Any] | None) -> TabRules:
        """Validate and convert the ``tabs.rules`` JSON.

        Unknown key, wrong type, invalid ``mode`` or ``min_s > max_s`` →
        ``ValidationError``.
        """
        root = _mapping(data, "rules", ("include", "exclude", "filters", "mode"))
        inc = _mapping(root.get("include"), "include", _RULE_INCLUDE_LISTS + _RULE_INCLUDE_FLAGS)
        exc = _mapping(root.get("exclude"), "exclude", _RULE_EXCLUDE_LISTS + ("shorts",))
        flt = _mapping(
            root.get("filters"), "filters", ("only_new", "per_channel", "min_s", "max_s")
        )
        inc_kw: dict[str, Any] = {
            k: _str_tuple(inc[k], f"include.{k}") for k in _RULE_INCLUDE_LISTS if k in inc
        }
        inc_kw.update({k: _flag(inc[k], f"include.{k}") for k in _RULE_INCLUDE_FLAGS if k in inc})
        exc_kw: dict[str, Any] = {
            k: _str_tuple(exc[k], f"exclude.{k}") for k in _RULE_EXCLUDE_LISTS if k in exc
        }
        exc_kw["shorts"] = _flag(exc.get("shorts", False), "exclude.shorts")
        include = RuleInclude(**inc_kw)
        exclude = RuleExclude(**exc_kw)
        filters = RuleFilters(
            only_new=_flag(flt.get("only_new", False), "filters.only_new"),
            per_channel=_opt_int(flt.get("per_channel"), "filters.per_channel", 1),
            min_s=_opt_int(flt.get("min_s"), "filters.min_s", 0),
            max_s=_opt_int(flt.get("max_s"), "filters.max_s", 0),
        )
        if (
            filters.min_s is not None
            and filters.max_s is not None
            and filters.min_s > filters.max_s
        ):
            raise ValidationError("filters: min_s > max_s", field="filters")
        mode_raw = root.get("mode", FeedMode.fresh.value)
        try:
            mode = FeedMode(mode_raw)
        except ValueError as exc_:
            raise ValidationError(f"invalid mode: {mode_raw!r}", field="mode") from exc_
        return cls(include=include, exclude=exclude, filters=filters, mode=mode)

    def to_dict(self) -> dict[str, Any]:
        """Full JSON (lists, not tuples), accepted back by ``from_dict``."""
        return {
            "include": {
                **{k: list(getattr(self.include, k)) for k in _RULE_INCLUDE_LISTS},
                **{k: getattr(self.include, k) for k in _RULE_INCLUDE_FLAGS},
            },
            "exclude": {
                **{k: list(getattr(self.exclude, k)) for k in _RULE_EXCLUDE_LISTS},
                "shorts": self.exclude.shorts,
            },
            "filters": {
                "only_new": self.filters.only_new,
                "per_channel": self.filters.per_channel,
                "min_s": self.filters.min_s,
                "max_s": self.filters.max_s,
            },
            "mode": self.mode.value,
        }


