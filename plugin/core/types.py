class Cancelled(Exception):
    """The job was cancelled (``job.cancel``): raised at the checkpoints of the ``JobRunner``'s
    ``on_progress``. It stays **outside** ``ERRORS``/``TubeError`` on purpose: it never becomes an
    error envelope (the job closes with ``error.code = JOB_CANCELLED_CODE``) and the core's
    ``except TubeError`` blocks do not mistake it for a search/AI failure."""

    code = "cancelled"

    def __init__(self, message: str = "Job cancelled.") -> None:
        super().__init__(message)
        self.message = message


def is_cancelled(on_progress: ProgressFn | None) -> bool:
    """``True`` if the job owning *on_progress* was cancelled (``False`` outside a job). Never
    raises."""
    probe = getattr(on_progress, "is_cancelled", None)
    if not callable(probe):
        return False
    try:
        return bool(probe())
    except Exception:  # noqa: BLE001 — probe; the next checkpoint decides
        return False


def check_cancelled(on_progress: ProgressFn | None) -> None:
    """Cooperative cancellation point: raises ``Cancelled`` if the job of *on_progress* was
    cancelled. Without a job (tool, ``/tube``, tests) it does nothing. Calling ``on_progress(...)``
    checks too."""
    check = getattr(on_progress, "check_cancelled", None)
    if callable(check):
        check()


