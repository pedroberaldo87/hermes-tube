class Refresher(Undoable, Protocol):
    """RSS refresh and reads (``core/refresh.py``; owner of ``watermarks`` and of the RSS
    ``meta`` keys)."""

    def refresh_all(
        self, *, timeout: float = 600.0, on_progress: ProgressFn | None = None
    ) -> RefreshReport:
        """Blocking: RSS of every ``subscribed``/``followed`` channel (4 at once), videos through
        ``VideoStore.upsert(origin=rss)``, stats through ``ChannelService.update_stats``, writes
        ``last_rss_at`` and emits ``refresh.done``. Timeout → ``partial`` report (does not raise).
        Honours the ``META_REFRESH_LOCK`` lock (another active cycle → ``Busy``)."""
        ...

    def refresh_channel(self, channel_id: str, *, timeout: float = 30.0) -> RefreshReport:
        """Blocking: one channel."""
        ...

    def kick_if_due(
        self, force: bool = False, *, wait: bool = False
    ) -> Literal["started", "skipped", "running"]:
        """Non-blocking unless ``wait=True`` (the cron script runs the cycle on its own thread).
        Without ``wait`` (< 50 ms, no network on the caller's thread): if the interval
        (``rss_interval_min`` since ``last_rss_at``) has passed or *force*, takes the lock in
        ``meta`` and starts a thread with ``refresh_all`` → ``"started"``; a cycle in progress →
        ``"running"``; otherwise ``"skipped"``. Called by ``GET /status``, ``/ext/state``,
        ``tube_status`` and ``POST /refresh``."""
        ...

    def kick_channel(self, channel_id: str) -> Literal["started", "running"]:
        """Non-blocking: refresh one channel in a thread (``POST /refresh/{channel_id}``)."""
        ...

    def is_running(self) -> bool:
        """There is an active cycle (valid lock)."""
        ...

    def last_rss_at(self) -> Timestamp | None:
        """End of the last cycle, even ``partial`` (cut by timeout) — otherwise a slow YouTube
        would make every ``/status`` start a new cycle."""
        ...

    def resolve_shorts(
        self, video_ids: Sequence[str], *, limit: int = 50, timeout: float = 20.0
    ) -> dict[str, bool]:
        """On-demand Short for stored videos with unknown ``is_short`` (in order, up to *limit*),
        4 at a time; stores through ``VideoStore.set_details``; an error on one only leaves it
        out. Returns ``video_id → is_short`` of what was resolved (the feed engine calls this,
        never YouTube directly)."""
        ...

    def mark_read(self, scope: ReadScope, *, actor: Actor = Actor.user) -> int:
        """Move ``watermarks.seen_up_to`` forward (channel, recursive folder, tab or everything);
        records ``mark_read``; returns how many channels changed."""
        ...

    def mark_read_changes(
        self, scope: ReadScope, *, actor: Actor = Actor.user
    ) -> tuple[int, tuple[int, ...]]:
        """``mark_read`` that also returns the ids of the history entries written
        (``POST /read`` → ``change_ids``; empty when nothing changed)."""
        ...

    def status(self) -> StatusSnapshot:
        """Body of ``GET /status``; read-only, fast (triggers nothing)."""
        ...

    def channel_totals(self) -> dict[str, int]:
        """``{"channels_total", "subscribed_total"}`` (``GET /status``): ``subscribed`` +
        ``followed`` channels (muted included) and ``subscribed`` only. One query."""
        ...


