# =========================================================================== profile and ctx

_LOCK = threading.RLock()
_CTX: dict[str, Any] = {}
# reload in the same process: each profile's Hermes ``ctx`` comes from the previous generation
_CTX.update(getattr(sys.modules.get("tube_pkg"), "__tube_ctx__", None) or {})
_DBS: dict[str, T.Db] = {}
_SETTINGS: dict[str, tuple[Any, T.Settings]] = {}
_GRAPHS: dict[str, Graph] = {}


def _test_db_path() -> str | None:
    value = os.environ.get(ENV_DB_PATH, "").strip()
    return value or None


def current_home() -> Path | None:
    """The Hermes profile active now (``None`` in test mode or outside Hermes)."""
    from tube_pkg.adapters.settings import resolve_home

    return resolve_home()


def home_key() -> str:
    """Key of the active profile (caches of ``ctx``, ``Settings`` and graph)."""
    test = _test_db_path()
    if test:
        return f"env:{test}"
    home = current_home()
    return str(home) if home is not None else "none"


def bind_ctx(ctx: Any) -> str:
    """Keep the ``register(ctx)`` ``ctx`` for the active profile (gateway). Returns the key."""
    key = home_key()
    with _LOCK:
        _CTX[key] = ctx
        _GRAPHS.pop(key, None)
        _SETTINGS.pop(key, None)
    return key


def get_ctx() -> Any:
    """``ctx`` of the active profile, or ``None`` (plugin host, scripts, tests)."""
    return _CTX.get(home_key())


def data_dir() -> Path:
    """``<profile>/plugin-data/<PLUGIN_ID>`` (created if needed); in test mode, the DB folder."""
    test = _test_db_path()
    if test:
        path = Path(test).expanduser().resolve().parent
        path.mkdir(parents=True, exist_ok=True)
        return path
    try:
        from plugins.plugin_storage import plugin_data_dir
    except ImportError as exc:
        raise RuntimeError(f"outside Hermes: set {ENV_DB_PATH}") from exc
    return Path(plugin_data_dir(PLUGIN_ID))


def db_path() -> str:
    """Database path of the active profile (without opening it)."""
    test = _test_db_path()
    if test:
        return str(Path(test).expanduser().resolve())
    from tube_pkg.adapters.storage import hermes_db_path

    path = hermes_db_path()
    if path is None:
        raise RuntimeError(f"outside Hermes: set {ENV_DB_PATH}")
    return path


# =========================================================================== infrastructure


def get_db() -> T.Db:
    """The ``Db`` of the active profile: one per file and process (``adapters/storage.open_db``)."""
    path = db_path()
    with _LOCK:
        db = _DBS.get(path)
        if db is None:
            from tube_pkg.adapters.storage import open_db

            db = open_db()
            _DBS[path] = db
        return db


def get_settings() -> T.Settings:
    """``Settings`` of the active profile (reads ``config.yaml`` on every use)."""
    key = home_key()
    ctx = get_ctx()
    with _LOCK:
        cached = _SETTINGS.get(key)
        if cached is not None and cached[0] is ctx:
            return cached[1]
        from tube_pkg.adapters.settings import build

        settings = build(ctx=ctx)
        _SETTINGS[key] = (ctx, settings)
        return settings


