def resolve_handler(module: str, name: str) -> Callable[..., Any]:
    """Function *name* of module *module* (late import; the attribute is read on every call so that
    ``monkeypatch`` works)."""
    return getattr(importlib.import_module(module), name)


def ext_handlers(*, db: T.Db, settings: T.Settings) -> Any:
    """``ExtHandlers`` (ext-protocol.md §9) with the services built on *db* — the same ``Db`` the
    extension server uses until it stops. Called by ``_server.ensure_server``."""
    from tube_pkg.ext._mount import ExtHandlers

    with _LOCK:
        g = next((x for x in _GRAPHS.values() if x.db is db and x.settings is settings), None)
    if g is None:
        g = Graph(db=db, settings=settings, ctx=get_ctx())
    fields: dict[str, Any] = {}
    for spec in EXT_HANDLERS:
        fn = resolve_handler(spec.module, spec.handler)
        fields[spec.handler] = functools.partial(fn, **{d: g.get(d) for d in spec.deps})
    auth = resolve_handler("tube_pkg.ext.auth", "authenticate")
    fields["authenticate"] = functools.partial(auth, devices=g.get("devices"))
    return ExtHandlers(**fields)


def _is_stub(obj: Any) -> bool:
    return bool(getattr(obj, "__contract_stub__", None))


def ensure_ext_server(*, role: str | None = None) -> int | None:
    """Start (or reuse) the extension server for the active profile and return the port (``None``
    → ``ext_endpoint_down``). Resolves database, settings and folder **here**, in the caller's
    context (``GET /status``, ``pair.start``, ``tube_status``). Never raises."""
    try:
        from tube_pkg.ext import _server

        db = get_db()
        settings = get_settings()
        ddir = data_dir()
        devices = get_devices()
        pairing_open = None if _is_stub(devices) else devices.pairing_open
        return _server.ensure_server(
            db=db, settings=settings, data_dir=ddir, pairing_open=pairing_open, role=role
        )
    except Exception:  # noqa: BLE001
        logger.exception("%s: ensure_ext_server failed", PLUGIN_ID)
        return None


def ext_endpoint_up() -> bool:
    """Does the active profile's extension server answer now? Never raises."""
    try:
        return bool(get_ext_endpoint_up()())
    except Exception:  # noqa: BLE001
        return False


def shutdown(home: Path | None = None, *, all_profiles: bool = False) -> None:
    """``on_unload``: stop the extension server **before** closing the database, then close the
    ``Db`` objects and forget ``ctx``/graph. *home* = the profile captured in ``register``."""
    from tube_pkg.ext import _server

    if all_profiles:
        _server.stop()
        prefix = None
    else:
        base = (home / "plugin-data" / PLUGIN_ID) if home is not None else None
        test = _test_db_path()
        if base is None and test:
            base = Path(test).expanduser().resolve().parent
        if base is not None:
            _server.stop_local(base)
        prefix = str(base.resolve()) if base is not None else None
    key = str(home) if home is not None else home_key()
    with _LOCK:
        for path in list(_DBS):
            if prefix is None or str(Path(path).resolve()).startswith(prefix):
                db = _DBS.pop(path)
                try:
                    db.close()
                except Exception:  # noqa: BLE001
                    logger.exception("%s: failed to close %s", PLUGIN_ID, path)
        if all_profiles:
            _CTX.clear()
            _GRAPHS.clear()
            _SETTINGS.clear()
        else:
            _CTX.pop(key, None)
            _GRAPHS.pop(key, None)
            _SETTINGS.pop(key, None)


