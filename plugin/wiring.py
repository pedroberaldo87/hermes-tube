"""Composition in a single place.

Connects the implementations (stub or real — whatever is in the module file) to the REST routes,
RPC methods, extension handlers, tools, ``/tube`` and the scripts.

Providers ``get_<name>()`` — one per dependency in ``BUILDS``/``DEPENDENCY_TYPES``
(``core/types.py``). Each returns the object of the **profile active now**: the service graph is
built lazily by each module's ``build(...)`` (signatures in ``BUILD_SIGNATURES``) and cached per
profile. Consumers call ``wiring.get_<name>()`` **at the time of use** (never keep the result in a
module variable).

- Unit tests swap ``wiring.get_<own>`` with ``monkeypatch`` (``wire`` fixture in ``conftest``);
  the graph honors the swap in the other services' dependencies too.
- Profile: in the gateway ``os.environ["HERMES_HOME"]`` is the **launch** profile; the right one
  comes from ``hermes_constants.get_hermes_home()`` (contextvar), which a new thread does **not**
  inherit. Resolve ``get_db()``/``get_settings()``/``data_dir()``/``get_<service>()`` **before**
  starting a thread and pass the objects to it (or use ``contextvars.copy_context().run``).
- Database: **one** ``Db`` per file/process (``get_db()``), alive until ``shutdown`` — the
  extension server uses the same object.
- ``TUBE_DB_PATH`` set (tests, worktrees): database in that file and ``Settings`` with defaults
  only; no real profile is touched.
- Integration: the real module replaces the stub at the same path with the same ``build``;
  nothing to change here, except ``get_lenses`` and the generated tables when the contract grows
  (``python scripts/gen_stubs.py``).

No network and no threads in this module.
"""

