class Graph:
    """Services built on one ``Db``/``Settings``/``ctx`` (one profile). Lazy, cached, thread-safe.
    ``get(name)`` honors a ``wiring.get_<name>`` swapped by monkeypatch."""

    def __init__(self, *, db: T.Db, settings: T.Settings, ctx: Any = None) -> None:
        self.db = db
        self.settings = settings
        self.ctx = ctx
        path = str(getattr(db, "path", "") or "")
        self.data_dir: Path | None = (
            Path(path).resolve().parent if path and path != ":memory:" else None
        )
        self._items: dict[str, Any] = {}
        self._building: set[str] = set()
        self._seeded = False
        self._lock = threading.RLock()

    def get(self, name: str) -> Any:
        provider = globals().get(f"get_{name}")
        if provider is not None and provider is not _ORIGINAL.get(name, provider):
            return provider()  # swapped by monkeypatch (unit tests)
        if name == "db":
            return self.db
        if name == "settings":
            return self.settings
        if name == "ctx":
            return self.ctx
        if name == "clock":
            return get_clock()
        if name == "lenses":
            return get_lenses()
        with self._lock:
            if name in self._items:
                return self._items[name]
            if name in self._building:
                raise RuntimeError(f"circular dependency in {name}")
            self._building.add(name)
            try:
                value = self._build(name)
            finally:
                self._building.discard(name)
            self._items[name] = value
            if name == "feed" and not self._building:
                # on-demand Shorts only through the Refresher, on every feed surface; the Refresher
                # depends on the engine, so it is born right after (attached in the branch below)
                try:
                    self.get("refresher")
                except Exception:  # noqa: BLE001 — a Refresher stub/error does not bring the feed down
                    logger.debug("refresher unavailable for the feed", exc_info=True)
            if name == "themes" and not self._building:
                # theme seeds the user does not follow also get new videos
                try:
                    if getattr(value, "fetch_seed", "absent") is None:
                        value.fetch_seed = self.get("refresher").refresh_channel
                except Exception:  # noqa: BLE001 — without a Refresher, only followed seeds refresh
                    logger.debug("refresher unavailable for the themes", exc_info=True)
            if name in ("feed", "sync", "tabs") and not self._building and not self._seeded:
                # built-in tabs exist before any reader (feed, /ext/state, Home)
                self._seeded = True
                try:
                    tabs = value if name == "tabs" else self.get("tabs")
                    seed = getattr(tabs, "ensure_builtin", None)
                    if callable(seed):
                        seed()
                except Exception:  # noqa: BLE001 — seeding tabs does not break whoever asked for the service
                    self._seeded = False
                    logger.debug("built-in tabs not seeded", exc_info=True)
            return value

    def _build(self, name: str) -> Any:
        if name == "ext_endpoint_up":
            ddir = self.data_dir or data_dir()
            return functools.partial(_endpoint_up, self.db, ddir)
        spec = _SPECS.get(name)
        if spec is None:
            raise KeyError(f"unknown dependency: {name}")
        module = importlib.import_module(_module_name(spec.module))
        factory = getattr(module, spec.function)
        kwargs = {dep: self.get(dep) for dep in spec.deps}
        for opt in spec.optional:
            if opt in ("clock", "ctx"):
                kwargs[opt] = self.get(opt)
        value = factory(**kwargs)
        if name == "refresher":
            # on-demand Shorts only through the Refresher, on every feed surface
            feed = self.get("feed")
            attach = getattr(feed, "attach_shorts_resolver", None)
            resolve = getattr(value, "resolve_shorts", None)
            if callable(attach) and callable(resolve):
                attach(resolve)
        return value

    def lens(self, provides_module: str = "plugin/core/extras_hn.py") -> T.Lens:
        """Build a lens through the module's ``build`` on this graph."""
        spec = next(s for s in T.BUILDS if s.module == provides_module)
        module = importlib.import_module(_module_name(spec.module))
        kwargs = {dep: self.get(dep) for dep in spec.deps}
        kwargs["clock"] = self.get("clock")
        return getattr(module, spec.function)(**kwargs)


def graph() -> Graph:
    """Graph of the active profile (rebuilt if ``db``/``settings``/``ctx`` changed)."""
    key = home_key()
    db = get_db()
    settings = get_settings()
    ctx = get_ctx()
    with _LOCK:
        g = _GRAPHS.get(key)
        if g is None or g.db is not db or g.settings is not settings or g.ctx is not ctx:
            g = Graph(db=db, settings=settings, ctx=ctx)
            _GRAPHS[key] = g
        return g


def reset() -> None:
    """Forget cached graphs and ``Settings`` (does not close databases). For tests."""
    with _LOCK:
        _GRAPHS.clear()
        _SETTINGS.clear()


