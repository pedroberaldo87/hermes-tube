"""The plugin's REST backend (``/api/plugins/<PLUGIN_ID>/…``), loaded by Hermes **by path**
(no package) — in the local Desktop, in a *plugin host* separate from the gateway.

Mounts every route of ``contract/api.yaml`` (``x-transport: rest``) from ``wiring.REST_ROUTES``
(generated by ``scripts/gen_stubs.py``): the handler is the ``<operationId in snake_case>``
function of the ``x-module`` (signature in ``plugin/api/_common.py``), imported on the first call
and looked up on every request (the real one replaces the stub without touching this file).

Rules: **always HTTP 200 + envelope** — a domain error becomes ``{"ok": false, "error": …}``, an
unexpected exception becomes ``internal`` (without the exception text), a body that is not a
JSON object becomes ``invalid``. The handler runs in a thread (``run_in_threadpool``): plain
``def`` routes, < 2 s, no AI and no events. The gateway strips ``Authorization``/cookies before
the host: no route receives an identity or ``ctx`` (settings through ``wiring.get_settings()``).
"""

from __future__ import annotations

import importlib
import importlib.util
import logging
from pathlib import Path
from typing import Any

from fastapi import APIRouter, Request
from fastapi.responses import JSONResponse
from starlette.concurrency import run_in_threadpool

# loaded by path: registers the tube_pkg alias and checks the code generation
_boot_path = Path(__file__).resolve().parent.parent / "_bootstrap.py"
_spec = importlib.util.spec_from_file_location("_tube_pkg_bootstrap_api", _boot_path)
if _spec is None or _spec.loader is None:
    raise ImportError(f"cannot load {_boot_path}")
_boot = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_boot)
_boot.ensure()
_boot.refresh(force=True)

from tube_pkg import wiring  # noqa: E402
from tube_pkg._id import PLUGIN_ID  # noqa: E402

logger = logging.getLogger(__name__)

router = APIRouter()


def _endpoint(route: wiring.RestRoute) -> Any:
    async def endpoint(request: Request) -> JSONResponse:
        # Hermes loads this file once per process: nothing from ``tube_pkg`` is pinned here —
        # the current generation is resolved on every request
        _boot.refresh()
        common = importlib.import_module("tube_pkg.api._common")
        try:
            raw = await request.body()
            body = common.parse_json_body(raw, method=request.method)
        except Exception as exc:  # noqa: BLE001 — bad body → invalid, never FastAPI's 422
            return JSONResponse(common.error_envelope(exc))
        query = dict(request.query_params)
        query.update({k: str(v) for k, v in request.path_params.items()})
        try:
            current = importlib.import_module("tube_pkg.wiring")
            fn = current.resolve_handler(route.module, route.handler)
        except Exception as exc:  # noqa: BLE001 — one broken module does not bring the rest down
            logger.exception(
                "%s: handler %s.%s unavailable", PLUGIN_ID, route.module, route.handler
            )
            return JSONResponse(common.error_envelope(exc))
        env = await run_in_threadpool(common.call_rest, fn, body, query)
        return JSONResponse(env)

    endpoint.__name__ = route.handler
    return endpoint


def _route_order(route: wiring.RestRoute) -> tuple[int, str]:
    # fixed paths before parameterized ones (/channels/batch before /channels/{id})
    return (route.path.count("{"), route.path)


for _route in sorted(wiring.REST_ROUTES, key=_route_order):
    router.add_api_route(
        _route.path,
        _endpoint(_route),
        methods=[_route.method],
        name=_route.operation_id,
        include_in_schema=False,
    )

__all__ = ["router"]
