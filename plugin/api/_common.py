"""Shared by the plugin surfaces: envelope, typed errors, ``@contract.real`` and the
signatures of the REST and RPC handlers.

Envelope (contract/api.yaml)::

    {"ok": True, "data": <JSON>}
    {"ok": False, "error": {"code", "message", "reason"?, "details"?}}

Handlers (one function per operation, in the contract's ``x-module``):

- **REST** (``plugin/api/<mod>.py``) — ``<operationId in snake_case>(body, query) -> Envelope``.
  ``body``: the JSON body (``None`` on GET/DELETE; ``{}`` on POST/PATCH without a body); ``query``:
  query **and** path parameters (``/channels/{id}`` → ``query["id"]``), always ``str``.
  Plain ``def`` route (runs in a thread), < 2 s, no AI, no events. May raise ``TubeError``:
  the router (``dashboard/plugin_api.py``) returns the error envelope with **HTTP 200**.
- **RPC** (``plugin/rpc/<mod>.py``) — ``<group>_<verb>(params, *, session_id=None, **kwargs)
  -> Envelope`` (``organize.run`` → ``organize_run``). ``register(ctx)`` wraps it with
  ``call_rpc``: never raises (exception → ``internal``), non-dict ``params`` → ``invalid``.
- **Extension** (``plugin/ext/<mod>.py``) — ``(device, body, query, *, <x-deps>) -> Envelope``
  (contract/ext-protocol.md §9; mounted by ``_mount.py`` via ``wiring.ext_handlers``).

Stub vs real: the stubs generated by ``scripts/gen_stubs.py`` carry
``@contract.stub("<operationId>")`` and return the contract's ``example``. The owning module
replaces the body and marks the function with ``@contract.real``: the surface test then requires
only the (strict) schema, not the example.
"""

from __future__ import annotations

import json
import logging
from collections.abc import Callable, Mapping
from types import SimpleNamespace
from typing import Any, TypeVar

from tube_pkg._id import PLUGIN_ID
from tube_pkg.core.types import (
    ERROR_HTTP_STATUS,
    ERRORS,
    PairingFailed,
    TubeError,
    UndoRefused,
    ValidationError,
    to_jsonable,
)

logger = logging.getLogger(__name__)

Envelope = dict[str, Any]
RestHandler = Callable[[Mapping[str, Any] | None, Mapping[str, str]], Envelope]
RpcHandler = Callable[..., Envelope]

ERROR_CODES: frozenset[str] = frozenset(ERROR_HTTP_STATUS)
"""Every error code in the contract (``x-error-codes``)."""

_F = TypeVar("_F", bound=Callable[..., Any])

_REAL_ATTR = "__contract_real__"
_STUB_ATTR = "__contract_stub__"


# =========================================================================== envelope


def ok(data: Any = None) -> Envelope:
    """``{"ok": True, "data": ...}`` with dataclasses/enums converted (``to_jsonable``)."""
    return {"ok": True, "data": to_jsonable(data)}


def fail(
    code: str,
    message: str = "",
    *,
    reason: str | None = None,
    details: Mapping[str, Any] | None = None,
) -> Envelope:
    """Error envelope. A code outside the contract becomes ``internal`` (logged: it is a bug)."""
    if code not in ERROR_CODES:
        logger.error("%s: error code not in the contract: %r", PLUGIN_ID, code)
        code, message = "internal", "internal error"
    error: dict[str, Any] = {"code": code, "message": message or code}
    if reason:
        error["reason"] = reason
    if details:
        error["details"] = to_jsonable(dict(details))
    return {"ok": False, "error": error}


def error_envelope(exc: BaseException) -> Envelope:
    """Exception → envelope. A ``TubeError`` becomes its own code (``PairingFailed`` uses its
    ``reason`` as the code; ``UndoRefused.reason`` goes into ``error.reason``); anything else
    becomes ``internal`` without the exception text (the log keeps the traceback)."""
    if isinstance(exc, PairingFailed):
        details = {k: v for k, v in exc.details.items() if k != "reason"}
        return fail(exc.reason, exc.message, details=details)
    if isinstance(exc, UndoRefused):
        return fail(exc.code, exc.message, reason=exc.reason, details=exc.details)
    if isinstance(exc, TubeError) and exc.code in ERROR_CODES:
        return fail(exc.code, exc.message, details=exc.details)
    logger.error("%s: unhandled error", PLUGIN_ID, exc_info=exc)
    return fail("internal", "internal error")


def is_envelope(value: Any) -> bool:
    if not isinstance(value, dict):
        return False
    if value.get("ok") is True:
        return "data" in value
    return value.get("ok") is False and isinstance(value.get("error"), dict)


# =========================================================================== stub × real


def _real(fn: _F) -> _F:
    """Mark the function as the real implementation: the surface test checks only the schema."""
    setattr(fn, _REAL_ATTR, True)
    return fn


def _stub(operation_id: str) -> Callable[[_F], _F]:
    """Mark a generated stub (returns the ``example`` of *operation_id*)."""

    def mark(fn: _F) -> _F:
        setattr(fn, _STUB_ATTR, operation_id)
        return fn

    return mark


contract = SimpleNamespace(real=_real, stub=_stub)
"""``@contract.real`` (owning module) and ``@contract.stub("<operationId>")`` (generator)."""


def is_real(fn: Any) -> bool:
    return bool(getattr(fn, _REAL_ATTR, False))


def stub_operation(fn: Any) -> str | None:
    """The stub's ``operationId`` (or RPC method name), ``None`` if it is not a stub."""
    return getattr(fn, _STUB_ATTR, None)


# =========================================================================== calls


def parse_json_body(raw: bytes | str | None, *, method: str) -> Mapping[str, Any] | None:
    """Body of a REST request: ``None`` on GET/DELETE, ``{}`` when empty on POST/PATCH; JSON that
    is not an object → ``ValidationError`` (becomes ``invalid``)."""
    if method.upper() in ("GET", "DELETE", "HEAD"):
        return None
    if raw is None or (isinstance(raw, bytes | str) and not raw.strip()):
        return {}
    try:
        data = json.loads(raw)
    except (ValueError, UnicodeDecodeError) as exc:
        raise ValidationError("body is not valid JSON") from exc
    if not isinstance(data, dict):
        raise ValidationError("body must be a JSON object")
    return data


def call_rest(
    fn: RestHandler, body: Mapping[str, Any] | None, query: Mapping[str, str]
) -> Envelope:
    """Call a REST handler and guarantee an envelope (error → envelope; never raises)."""
    try:
        env = fn(body, query)
    except Exception as exc:  # noqa: BLE001 — REST always answers 200 + envelope
        return error_envelope(exc)
    if not is_envelope(env):
        logger.error("%s: REST handler %s returned a non-envelope", PLUGIN_ID, _name(fn))
        return fail("internal", "internal error")
    return env


def call_rpc(
    fn: RpcHandler, params: Any, *, session_id: str | None = None, **kwargs: Any
) -> Envelope:
    """Call an RPC handler: non-dict ``params`` → ``invalid``; exception → envelope (never
    raises)."""
    if params is None:
        params = {}
    if not isinstance(params, dict):
        return fail("invalid", "params must be an object")
    try:
        env = fn(params, session_id=session_id, **kwargs)
    except Exception as exc:  # noqa: BLE001 — RPC never raises (rpc.yaml)
        return error_envelope(exc)
    if not is_envelope(env):
        logger.error("%s: RPC handler %s returned a non-envelope", PLUGIN_ID, _name(fn))
        return fail("internal", "internal error")
    return env


def _name(fn: Any) -> str:
    return f"{getattr(fn, '__module__', '?')}.{getattr(fn, '__qualname__', repr(fn))}"


